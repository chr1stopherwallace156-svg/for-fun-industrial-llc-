assert.equal(one.external_actions,0);
assert.equal(one.checks.multiple_source_domains,false);
const two=assessEvidence({records:[base,{...base,source_url:"https://example.net/b",score:8}]});
assert.equal(two.checks.multiple_source_domains,true);
assert.equal(two.conflicts.includes("operator_supplied_scores_disagree"),true);

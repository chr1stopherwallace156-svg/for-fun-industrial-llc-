import assert from "node:assert/strict";
import {assessEvidence} from "./evidence-verifier-v1.mjs";
const base={plan_id:"070b202f-1a78-41ae-aaec-7f8cc859417b",task_id:"OP1-DEMAND",criterion:"demand",source_url:"https://example.org/a",title:"Synthetic source",observation:"Synthetic observation",observed_utc:"2026-11-13T12:00:00Z",score:6};
const one=assessEvidence({records:[base]});
assert.equal(one.verification_status,"unverified_requires_source_inspection");
